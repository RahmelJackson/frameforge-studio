function textOf(label){for(const node of label.childNodes){if(node.nodeType===3&&node.textContent.trim())return node.textContent.trim();if(node.nodeType===1&&node.matches('span:not(.setting-tip)'))return node.textContent.trim();}return '';}
function attach(root=document){
 for(const label of root.querySelectorAll('label:not([data-tipped])')){
  label.dataset.tipped='1';
  const control=label.querySelector('input,select,textarea')??(label.htmlFor?document.getElementById(label.htmlFor):null);
  if(!control||control.type==='file')continue;
  const text=textOf(label);const tip=byId[control.id]??byLabel[text.toLowerCase().replace(/\s*\(.*\)$/,'')];
  if(!tip)continue;
  const button=document.createElement('button');button.type='button';button.className='setting-tip';button.dataset.tip=tip;button.textContent='i';
  button.setAttribute('aria-label','What is '+(text||'this setting')+'?');button.setAttribute('aria-describedby','setting-tip-bubble');button.setAttribute('aria-expanded','false');
  const anchor=[...label.childNodes].find(n=>n.nodeType===3&&n.textContent.trim()||n.nodeType===1&&n.matches('span:not(.setting-tip):not(.setting-label-row)'));
  if(control.type==='checkbox'||control.type==='radio'){const span=label.querySelector('span');(span??label).append(button);}
  else if(anchor){const row=document.createElement('span');row.className='setting-label-row';anchor.replaceWith(row);row.append(anchor,button);}else label.prepend(button);
 }
}
